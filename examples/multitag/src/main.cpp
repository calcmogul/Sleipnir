// Determines a robot's 6-DOF pose from the corner pixel locations of several
// AprilTags.
//
// The robot's pose is an SE(3) decision variable, whose rotation the solver
// keeps unit length.

#include <print>
#include <ranges>
#include <utility>
#include <vector>

#include <Eigen/Core>
#include <Eigen/Geometry>
#include <sleipnir/autodiff/pose3.hpp>
#include <sleipnir/autodiff/translation3.hpp>
#include <sleipnir/autodiff/variable.hpp>
#include <sleipnir/autodiff/variable_matrix.hpp>
#include <sleipnir/optimization/problem.hpp>

int main() {
  slp::Problem<double> problem;

  // camera calibration
  constexpr double fx = 600;
  constexpr double fy = 600;
  constexpr double cx = 300;
  constexpr double cy = 150;

  // robot pose. Its initial guess is the default, the field origin with no
  // rotation.
  auto field2robot = problem.decision_variable(slp::se3);

  // robot is ENU, cameras are SDE
  const slp::Pose3<double> robot2camera{Eigen::Vector3d::Zero(),
                                        Eigen::Quaterniond{Eigen::Matrix3d{
                                            {0, 0, 1},
                                            {-1, 0, 0},
                                            {0, -1, 0},
                                        }}};

  auto camera2field = (field2robot * robot2camera).inverse();

  // Corners of two AprilTags in field space. Each tag faces the robot (−x).
  std::vector field2points{
      Eigen::Vector3d{2.0, -0.48255, 0.51745},
      Eigen::Vector3d{2.0, -0.31745, 0.51745},
      Eigen::Vector3d{2.0, -0.31745, 0.68255},
      Eigen::Vector3d{2.0, -0.48255, 0.68255},
      Eigen::Vector3d{2.4, 0.41745, 0.91745},
      Eigen::Vector3d{2.4, 0.58255, 0.91745},
      Eigen::Vector3d{2.4, 0.58255, 1.08255},
      Eigen::Vector3d{2.4, 0.41745, 1.08255},
  };

  // List of pixel locations we saw the corners at. These were generated by
  // projecting the corners from a robot at position (0.2, −0.1, 0.5) m with
  // yaw 10°, pitch −5°, and roll 3°, which is the quaternion
  // (w, x, y, z) = (0.9948, 0.0299, −0.0412, 0.0882).
  std::vector point_observations{
      std::pair{545.196, 183.529}, std::pair{484.874, 186.792},
      std::pair{480.388, 129.989}, std::pair{540.129, 125.807},
      std::pair{263.526, 94.255},  std::pair{221.887, 97.798},
      std::pair{220.151, 55.775},  std::pair{261.507, 51.731},
  };

  // Cost
  slp::Variable J = 0.0;
  for (const auto& [field2point, observation] :
       std::views::zip(field2points, point_observations)) {
    // point's coordinates in camera frame
    auto camera2point =
        slp::Translation3<double>{field2point}.transform_by(camera2field);
    const auto& x = camera2point.x();
    const auto& y = camera2point.y();
    const auto& z = camera2point.z();

    // coordinates observed at
    auto [u_observed, v_observed] = observation;

    auto u = fx * x / z + cx;
    auto v = fy * y / z + cy;

    auto u_err = u - u_observed;
    auto v_err = v - v_observed;

    // Cost function is square of reprojection error
    J += u_err * u_err + v_err * v_err;
  }

  problem.minimize(J);

  problem.solve({.diagnostics = true});

  auto robot_position = field2robot.translation().value();
  std::println("x = {} m", robot_position.x());
  std::println("y = {} m", robot_position.y());
  std::println("z = {} m", robot_position.z());

  auto q = field2robot.rotation().value();
  std::println("q = ({}, {}, {}, {})", q.w(), q.x(), q.y(), q.z());
}

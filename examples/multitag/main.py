#!/usr/bin/env python

"""
Determines a robot's 6-DOF pose from the corner pixel locations of several
AprilTags.

The robot's pose is an SE(3) decision variable, whose rotation the solver keeps
unit length.
"""

import numpy as np
from sleipnir.autodiff import Pose3, Rotation3, Translation3
from sleipnir.optimization import Problem, se3


def main() -> None:
    problem = Problem()

    # camera calibration
    fx = 600
    fy = 600
    cx = 300
    cy = 150

    # robot pose. Its initial guess is the default, the field origin with no
    # rotation.
    field2robot = problem.decision_variable(se3)

    # robot is ENU, cameras are SDE. This is the rotation matrix
    # [[0, 0, 1], [-1, 0, 0], [0, -1, 0]].
    robot2camera = Pose3(np.zeros(3), Rotation3(0.5, -0.5, 0.5, -0.5))

    camera2field = (field2robot * robot2camera).inverse()

    # Corners of two AprilTags in field space. Each tag faces the robot (−x).
    field2points = [
        np.array([2.0, -0.48255, 0.51745]),
        np.array([2.0, -0.31745, 0.51745]),
        np.array([2.0, -0.31745, 0.68255]),
        np.array([2.0, -0.48255, 0.68255]),
        np.array([2.4, 0.41745, 0.91745]),
        np.array([2.4, 0.58255, 0.91745]),
        np.array([2.4, 0.58255, 1.08255]),
        np.array([2.4, 0.41745, 1.08255]),
    ]

    # List of pixel locations we saw the corners at. These were generated by
    # projecting the corners from a robot at position (0.2, −0.1, 0.5) m with
    # yaw 10°, pitch −5°, and roll 3°, which is the quaternion
    # (w, x, y, z) = (0.9948, 0.0299, −0.0412, 0.0882).
    point_observations = [
        (545.196, 183.529),
        (484.874, 186.792),
        (480.388, 129.989),
        (540.129, 125.807),
        (263.526, 94.255),
        (221.887, 97.798),
        (220.151, 55.775),
        (261.507, 51.731),
    ]

    # Cost
    J = 0
    for field2point, observation in zip(field2points, point_observations):
        # point's coordinates in camera frame
        camera2point = Translation3(field2point).transform_by(camera2field)
        x = camera2point.x()
        y = camera2point.y()
        z = camera2point.z()

        # coordinates observed at
        u_observed, v_observed = observation

        u = fx * x / z + cx
        v = fy * y / z + cy

        u_err = u - u_observed
        v_err = v - v_observed

        # Cost function is square of reprojection error
        J += u_err**2 + v_err**2

    problem.minimize(J)

    problem.solve(diagnostics=True)

    x, y, z = field2robot.translation().value()
    print(f"x = {x} m")
    print(f"y = {y} m")
    print(f"z = {z} m")

    w, qx, qy, qz = field2robot.rotation().value()
    print(f"q = ({w}, {qx}, {qy}, {qz})")


if __name__ == "__main__":
    main()

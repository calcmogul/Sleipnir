#!/usr/bin/env python

"""
Determines a robot's 6-DOF pose from the corner pixel locations of several
AprilTags when one corner was misdetected.

Glare on a tag moved one detected corner 30 px from where it really is. A least
squares fit of the reprojection error lets that one corner pull the whole pose
off. A Huber loss grows only linearly for large errors, so the misdetected
corner's pull on the pose is bounded, but it still biases the pose. A
Geman–McClure loss levels off for large errors, so a corner far from the fit
has almost no pull, and the other seven corners determine the pose.

The Geman–McClure loss isn't convex, so a poor initial guess can converge to a
wrong pose: far from the fit every corner looks like an outlier. The Huber loss
is convex in the reprojection error, so its fit is solved first and used as the
initial guess (a two-step version of graduated non-convexity; Yang et al.,
"Graduated Non-Convexity for Robust Spatial Perception", RA-L 2020).
"""

import math
from collections.abc import Callable

import numpy as np
from scipy.spatial.transform import Rotation
from sleipnir.autodiff import Pose3, Real, Rotation3, Translation3, sqrt
from sleipnir.optimization import Problem


def solve(
    field2points: list[np.ndarray],
    point_observations: list[tuple[float, float]],
    loss: Callable[[Real], Real],
    initial_position: np.ndarray,
    initial_q: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Finds the robot pose that minimizes the sum of loss(r²) over the corners,
    where r is a corner's reprojection error in pixels, starting from the given
    initial guess.

    Rotations are (w, x, y, z) quaternions. Returns the robot's position and
    rotation.
    """
    problem = Problem()

    # camera calibration
    fx = 600
    fy = 600
    cx = 300
    cy = 150

    # robot pose
    field2robot = problem.pose3_decision_variable()
    field2robot.translation().set_value(initial_position)
    field2robot.rotation().set_value(*initial_q)

    # robot is ENU, cameras are SDE. This is the rotation matrix
    # [[0, 0, 1], [-1, 0, 0], [0, -1, 0]].
    robot2camera = Pose3(np.zeros(3), Rotation3(0.5, -0.5, 0.5, -0.5))

    camera2field = (field2robot * robot2camera).inverse()

    J = 0
    for field2point, observation in zip(field2points, point_observations):
        # point's coordinates in camera frame
        camera2point = Translation3(field2point).transform_by(camera2field)
        x = camera2point.x()
        y = camera2point.y()
        z = camera2point.z()

        # coordinates observed at
        u_observed, v_observed = observation

        u = fx * x / z + cx
        v = fy * y / z + cy

        u_err = u - u_observed
        v_err = v - v_observed

        J += loss(u_err**2 + v_err**2)

    problem.minimize(J)

    problem.solve()

    return np.array(field2robot.translation().value()), np.array(
        field2robot.rotation().value()
    )


def main() -> None:
    # Corners of two AprilTags in field space. Each tag faces the robot (−x).
    field2points = [
        np.array([2.0, -0.48255, 0.51745]),
        np.array([2.0, -0.31745, 0.51745]),
        np.array([2.0, -0.31745, 0.68255]),
        np.array([2.0, -0.48255, 0.68255]),
        np.array([2.4, 0.41745, 0.91745]),
        np.array([2.4, 0.58255, 0.91745]),
        np.array([2.4, 0.58255, 1.08255]),
        np.array([2.4, 0.41745, 1.08255]),
    ]

    # List of pixel locations we saw the corners at. These were generated by
    # projecting the corners from a robot at position (0.2, −0.1, 0.5) m with
    # yaw 10°, pitch −5°, and roll 3°. The second tag's third corner was really
    # at (220.151, 55.775), but glare moved its detection 30 px.
    point_observations = [
        (545.196, 183.529),
        (484.874, 186.792),
        (480.388, 129.989),
        (540.129, 125.807),
        (263.526, 94.255),
        (221.887, 97.798),
        (244.151, 73.775),
        (261.507, 51.731),
    ]

    true_position = np.array([0.2, -0.1, 0.5])
    true_rotation = Rotation.from_euler("ZYX", [10.0, -5.0, 3.0], degrees=True)

    # Least squares
    def least_squares(r_sq: Real) -> Real:
        return r_sq

    # Pseudo-Huber loss, δ²(√(1 + r²/δ²) − 1). It's r²/2 for r ≪ δ and grows like
    # δ|r| for r ≫ δ, so a corner's pull on the pose is at most δ. Unlike the
    # exact Huber loss, it's smooth everywhere, so Newton's method converges
    # quickly. Corners within δ of the fit get least squares weight, so δ should
    # be at least the detection noise, which is about 1 px for AprilTags.
    δ = 1.0

    def huber(r_sq: Real) -> Real:
        return δ**2 * (sqrt(1.0 + r_sq / δ**2) - 1.0)

    # Geman–McClure loss, r²/(c² + r²). It's r²/c² for r ≪ c and levels off at 1
    # for r ≫ c, so a corner's pull on the pose falls off like c²/r³. c is a few
    # times the detection noise.
    c = 2.0

    def geman_mcclure(r_sq: Real) -> Real:
        return r_sq / (c**2 + r_sq)

    # The least squares and Huber fits start from the field origin with no
    # rotation. The Geman–McClure fit starts from the Huber fit.
    origin_position = np.zeros(3)
    origin_q = np.array([1.0, 0.0, 0.0, 0.0])
    least_squares_pose = solve(
        field2points, point_observations, least_squares, origin_position, origin_q
    )
    huber_pose = solve(
        field2points, point_observations, huber, origin_position, origin_q
    )
    geman_mcclure_pose = solve(
        field2points, point_observations, geman_mcclure, *huber_pose
    )

    for name, (robot_position, q) in [
        ("Least squares", least_squares_pose),
        ("Huber", huber_pose),
        ("Geman–McClure", geman_mcclure_pose),
    ]:
        position_error = np.linalg.norm(robot_position - true_position)

        # SciPy quaternions are (x, y, z, w)
        rotation = Rotation.from_quat([q[1], q[2], q[3], q[0]])
        rotation_error = (rotation * true_rotation.inv()).magnitude()

        x, y, z = robot_position
        print(name)
        print(f"  x = {x} m")
        print(f"  y = {y} m")
        print(f"  z = {z} m")
        print(f"  q = ({q[0]}, {q[1]}, {q[2]}, {q[3]})")
        print(f"  position error = {100.0 * position_error} cm")
        print(f"  rotation error = {math.degrees(rotation_error)}°")


if __name__ == "__main__":
    main()

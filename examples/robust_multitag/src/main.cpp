// Determines a robot's 6-DOF pose from the corner pixel locations of several
// AprilTags when one corner was misdetected.
//
// Glare on a tag moved one detected corner 30 px from where it really is. A
// least squares fit of the reprojection error lets that one corner pull the
// whole pose off. A Huber loss grows only linearly for large errors, so the
// misdetected corner's pull on the pose is bounded, but it still biases the
// pose. A Geman–McClure loss levels off for large errors, so a corner far from
// the fit has almost no pull, and the other seven corners determine the pose.
//
// The Geman–McClure loss isn't convex, so a poor initial guess can converge to
// a wrong pose: far from the fit every corner looks like an outlier. The Huber
// loss is convex in the reprojection error, so its fit is solved first and
// used as the initial guess (a two-step version of graduated non-convexity;
// Yang et al., "Graduated Non-Convexity for Robust Spatial Perception",
// RA-L 2020).

#include <functional>
#include <numbers>
#include <print>
#include <ranges>
#include <utility>
#include <vector>

#include <Eigen/Core>
#include <Eigen/Geometry>
#include <sleipnir/autodiff/pose3.hpp>
#include <sleipnir/autodiff/real.hpp>
#include <sleipnir/autodiff/translation3.hpp>
#include <sleipnir/optimization/problem.hpp>

// Finds the robot pose that minimizes the sum of loss(r²) over the corners,
// where r is a corner's reprojection error in pixels, starting from the given
// initial guess.
slp::Pose3<double> solve(
    const std::vector<Eigen::Vector3d>& field2points,
    const std::vector<std::pair<double, double>>& point_observations,
    std::function<slp::Real<double>(const slp::Real<double>&)> loss,
    slp::Pose3<double> initial_field2robot) {
  slp::Problem<double> problem;

  // camera calibration
  constexpr double fx = 600;
  constexpr double fy = 600;
  constexpr double cx = 300;
  constexpr double cy = 150;

  // robot pose
  auto field2robot = problem.pose3_decision_variable();
  field2robot.translation().set_value(
      initial_field2robot.translation().value());
  field2robot.rotation().set_value(initial_field2robot.rotation().value());

  // robot is ENU, cameras are SDE
  const slp::Pose3<double> robot2camera{Eigen::Vector3d::Zero(),
                                        Eigen::Quaterniond{Eigen::Matrix3d{
                                            {0, 0, 1},
                                            {-1, 0, 0},
                                            {0, -1, 0},
                                        }}};

  auto camera2field = (field2robot * robot2camera).inverse();

  slp::Real J = 0.0;
  for (const auto& [field2point, observation] :
       std::views::zip(field2points, point_observations)) {
    // point's coordinates in camera frame
    auto camera2point =
        slp::Translation3<double>{field2point}.transform_by(camera2field);
    const auto& x = camera2point.x();
    const auto& y = camera2point.y();
    const auto& z = camera2point.z();

    // coordinates observed at
    auto [u_observed, v_observed] = observation;

    auto u = fx * x / z + cx;
    auto v = fy * y / z + cy;

    auto u_err = u - u_observed;
    auto v_err = v - v_observed;

    J += loss(u_err * u_err + v_err * v_err);
  }

  problem.minimize(J);

  problem.solve();

  return slp::Pose3<double>{field2robot.translation().value(),
                            field2robot.rotation().value()};
}

int main() {
  // Corners of two AprilTags in field space. Each tag faces the robot (−x).
  std::vector field2points{
      Eigen::Vector3d{2.0, -0.48255, 0.51745},
      Eigen::Vector3d{2.0, -0.31745, 0.51745},
      Eigen::Vector3d{2.0, -0.31745, 0.68255},
      Eigen::Vector3d{2.0, -0.48255, 0.68255},
      Eigen::Vector3d{2.4, 0.41745, 0.91745},
      Eigen::Vector3d{2.4, 0.58255, 0.91745},
      Eigen::Vector3d{2.4, 0.58255, 1.08255},
      Eigen::Vector3d{2.4, 0.41745, 1.08255},
  };

  // List of pixel locations we saw the corners at. These were generated by
  // projecting the corners from a robot at position (0.2, −0.1, 0.5) m with
  // yaw 10°, pitch −5°, and roll 3°. The second tag's third corner was really
  // at (220.151, 55.775), but glare moved its detection 30 px.
  std::vector point_observations{
      std::pair{545.196, 183.529}, std::pair{484.874, 186.792},
      std::pair{480.388, 129.989}, std::pair{540.129, 125.807},
      std::pair{263.526, 94.255},  std::pair{221.887, 97.798},
      std::pair{244.151, 73.775},  std::pair{261.507, 51.731},
  };

  const Eigen::Vector3d true_position{0.2, -0.1, 0.5};
  const Eigen::Quaterniond true_rotation{
      Eigen::AngleAxisd{10.0 * std::numbers::pi / 180.0,
                        Eigen::Vector3d::UnitZ()} *
      Eigen::AngleAxisd{-5.0 * std::numbers::pi / 180.0,
                        Eigen::Vector3d::UnitY()} *
      Eigen::AngleAxisd{3.0 * std::numbers::pi / 180.0,
                        Eigen::Vector3d::UnitX()}};

  // Least squares
  auto least_squares = [](const slp::Real<double>& r_sq) { return r_sq; };

  // Pseudo-Huber loss, δ²(√(1 + r²/δ²) − 1). It's r²/2 for r ≪ δ and grows like
  // δ|r| for r ≫ δ, so a corner's pull on the pose is at most δ. Unlike the
  // exact Huber loss, it's smooth everywhere, so Newton's method converges
  // quickly. Corners within δ of the fit get least squares weight, so δ should
  // be at least the detection noise, which is about 1 px for AprilTags.
  constexpr double δ = 1.0;
  auto huber = [](const slp::Real<double>& r_sq) {
    return δ * δ * (slp::sqrt(1.0 + r_sq / (δ * δ)) - 1.0);
  };

  // Geman–McClure loss, r²/(c² + r²). It's r²/c² for r ≪ c and levels off at 1
  // for r ≫ c, so a corner's pull on the pose falls off like c²/r³. c is a few
  // times the detection noise.
  constexpr double c = 2.0;
  auto geman_mcclure = [](const slp::Real<double>& r_sq) {
    return r_sq / (c * c + r_sq);
  };

  // The least squares and Huber fits start from the field origin with no
  // rotation. The Geman–McClure fit starts from the Huber fit.
  const slp::Pose3<double> field_origin{Eigen::Vector3d::Zero(),
                                        Eigen::Quaterniond::Identity()};
  auto least_squares_field2robot =
      solve(field2points, point_observations, least_squares, field_origin);
  auto huber_field2robot =
      solve(field2points, point_observations, huber, field_origin);
  auto geman_mcclure_field2robot =
      solve(field2points, point_observations, geman_mcclure, huber_field2robot);

  for (auto [name, field2robot] :
       {std::pair{"Least squares", least_squares_field2robot},
        std::pair{"Huber", huber_field2robot},
        std::pair{"Geman–McClure", geman_mcclure_field2robot}}) {
    auto robot_position = field2robot.translation().value();
    auto q = field2robot.rotation().value();

    double position_error = (robot_position - true_position).norm();
    double rotation_error = q.angularDistance(true_rotation);

    std::println("{}", name);
    std::println("  x = {} m", robot_position.x());
    std::println("  y = {} m", robot_position.y());
    std::println("  z = {} m", robot_position.z());
    std::println("  q = ({}, {}, {}, {})", q.w(), q.x(), q.y(), q.z());
    std::println("  position error = {} cm", 100.0 * position_error);
    std::println("  rotation error = {}°",
                 rotation_error * 180.0 / std::numbers::pi);
  }
}

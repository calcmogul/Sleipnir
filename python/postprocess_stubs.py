#!/usr/bin/env python

"""
Fixes up type stubs generated by nanobind's stubgen.

stubgen can't express some things the bindings support at runtime:

1. Implicit conversions widen what parameters accept: RealSubmatrix converts to
   RealMatrix, float converts to Real, complex and Real convert to Complex, and
   ComplexSubmatrix and RealMatrix convert to ComplexMatrix. Every RealMatrix
   parameter also accepts a RealSubmatrix, and every ComplexMatrix parameter
   also accepts a ComplexSubmatrix and a RealMatrix. Every Real parameter also
   accepts a float, and every Complex parameter also accepts a complex and a
   Real. Return types and callback arguments are left alone since those are
   never widened types.
   Sparse matrix parameters annotated as scipy.sparse.csc_matrix also accept
   scipy.sparse.csr_matrix.
2. Sparse matrices are annotated as scipy.sparse.csc_matrix[float] or
   scipy.sparse.csc_matrix[complex], but scipy-stubs expects a NumPy numeric
   scalar type argument.
"""

import argparse
import ast
import re
from dataclasses import dataclass
from pathlib import Path

PREFIX = r"(?:sleipnir\._sleipnir\.autodiff\.)?"

# RealMatrix, optionally module-qualified. The lookahead prevents already-widened
# annotations from matching again.
#
#   x: RealMatrix | None
#   -> x: RealMatrix | RealSubmatrix | None
MATRIX = re.compile(
    rf"""
    (?<![\w.])                         # Not part of another name
    ({PREFIX})                         # Optional module prefix
    RealMatrix\b                       # Type name
    (?!\ \|\ {PREFIX}RealSubmatrix\b)  # Not already widened
    """,
    re.VERBOSE,
)

# Real, optionally module-qualified. The lookahead prevents already-widened
# annotations from matching again.
#
#   x: Sequence[Real]
#   -> x: Sequence[Real | float]
REAL = re.compile(
    rf"""
    (?<![\w.])         # Not part of another name
    ({PREFIX})         # Optional module prefix
    Real\b             # Type name
    (?!\ \|\ float\b)  # Not already widened
    """,
    re.VERBOSE,
)


# ComplexMatrix, optionally module-qualified. The lookahead prevents
# already-widened annotations from matching again.
#
#   x: ComplexMatrix | None
#   -> x: ComplexMatrix | RealMatrix | None
COMPLEX_MATRIX = re.compile(
    rf"""
    (?<![\w.])                      # Not part of another name
    ({PREFIX})                      # Optional module prefix
    ComplexMatrix\b                 # Type name
    (?!\ \|\ {PREFIX}RealMatrix\b)  # Not already widened
    """,
    re.VERBOSE,
)

# ComplexMatrix, optionally module-qualified. The lookahead prevents
# already-widened annotations from matching again.
#
#   x: ComplexMatrix | RealMatrix | None
#   -> x: ComplexMatrix | ComplexSubmatrix | RealMatrix | None
COMPLEX_MATRIX_FOR_SUBMATRIX = re.compile(
    rf"""
    (?<![\w.])                            # Not part of another name
    ({PREFIX})                            # Optional module prefix
    ComplexMatrix\b                       # Type name
    (?!\ \|\ {PREFIX}ComplexSubmatrix\b)  # Not already widened
    """,
    re.VERBOSE,
)

# Complex, optionally module-qualified. The lookahead prevents already-widened
# annotations from matching again.
#
#   x: Complex | None
#   -> x: Complex | complex | None
COMPLEX = re.compile(
    rf"""
    (?<![\w.])           # Not part of another name
    ({PREFIX})           # Optional module prefix
    Complex\b            # Type name
    (?!\ \|\ complex\b)  # Not already widened
    """,
    re.VERBOSE,
)

# Complex, optionally module-qualified and already widened with complex. The
# possessive quantifier keeps the complex from being dropped to get past the
# lookahead, which prevents already-widened annotations from matching again.
#
#   x: Complex | complex | None
#   -> x: Complex | complex | Real | None
COMPLEX_FOR_REAL = re.compile(
    rf"""
    (?<![\w.])                    # Not part of another name
    ({PREFIX})                    # Optional module prefix
    Complex\b                     # Type name
    (\ \|\ complex\b)?+           # Optional complex widening
    (?!\ \|\ {PREFIX}Real\b)      # Not already widened
    """,
    re.VERBOSE,
)


# A CSC sparse matrix parameter. The bindings also accept CSR sparse matrices,
# which nanobind converts. The lookahead prevents already-widened annotations
# from matching again.
#
#   x: scipy.sparse.csc_matrix[float]
#   -> x: scipy.sparse.csc_matrix[float] | scipy.sparse.csr_matrix[float]
SPARSE = re.compile(
    r"""
    (?<![\w.])                             # Not part of another name
    scipy\.sparse\.csc_matrix\[(\w+)\]       # Type name and scalar type
    (?!\ \|\ scipy\.sparse\.csr_matrix\b)    # Not already widened
    """,
    re.VERBOSE,
)


@dataclass(frozen=True)
class Widening:
    """A type that also accepts another type via implicit conversion."""

    # Matches the narrow type
    pattern: re.Pattern[str]

    # Replaces the narrow type with the type that converts to it
    source: str

    # Replaces the narrow type with the widened type
    widened: str


# \1 is "sleipnir._sleipnir.autodiff." prefix or empty
WIDENINGS = [
    Widening(
        SPARSE,
        r"scipy.sparse.csr_matrix[\1]",
        r"scipy.sparse.csc_matrix[\1] | scipy.sparse.csr_matrix[\1]",
    ),
    Widening(COMPLEX_MATRIX, r"\1RealMatrix", r"\1ComplexMatrix | \1RealMatrix"),
    Widening(
        COMPLEX_MATRIX_FOR_SUBMATRIX,
        r"\1ComplexSubmatrix",
        r"\1ComplexMatrix | \1ComplexSubmatrix",
    ),
    Widening(COMPLEX, "complex", r"\1Complex | complex"),
    Widening(COMPLEX_FOR_REAL, r"\1Real", r"\1Complex\2 | \1Real"),
    Widening(MATRIX, r"\1RealSubmatrix", r"\1RealMatrix | \1RealSubmatrix"),
    Widening(REAL, "float", r"\1Real | float"),
]


def is_callable(annotation: ast.expr) -> bool:
    """Returns True if an annotation contains a Callable type."""
    return any(
        (isinstance(node, ast.Name) and node.id == "Callable")
        or (isinstance(node, ast.Attribute) and node.attr == "Callable")
        for node in ast.walk(annotation)
    )


def is_nested(annotation: ast.expr, pattern: re.Pattern[str]) -> bool:
    """
    Returns True if a type matching the pattern appears inside a subscript of an
    annotation (e.g., Real in Sequence[Real]).
    """
    return any(
        isinstance(node, ast.Subscript) and pattern.search(ast.unparse(node.slice))
        for node in ast.walk(annotation)
    )


def parameters(node: ast.FunctionDef) -> list[ast.arg | None]:
    """Returns a function's parameters in signature order."""
    args = node.args
    return [
        *args.posonlyargs,
        None,  # Separates positional-only parameters from the rest
        *args.args,
        args.vararg,
        *args.kwonlyargs,
        args.kwarg,
    ]


def signature(node: ast.FunctionDef) -> list[str | None]:
    """Returns a function's parameter annotations as source strings."""
    return [
        None if arg is None or arg.annotation is None else ast.unparse(arg.annotation)
        for arg in parameters(node)
    ]


def widen_signatures(stub: str) -> str:
    """
    Widens every RealMatrix in function parameter annotations to
    RealMatrix | RealSubmatrix, every Real to Real | float, every Complex to
    Complex | complex | Real | float, and every ComplexMatrix to
    ComplexMatrix | ComplexSubmatrix | RealMatrix | RealSubmatrix.

    A parameter isn't widened if a sibling overload is identical except it takes
    the source type there (e.g., float instead of Real); widening it would make
    that overload unreachable. Types nested in a subscript (e.g.,
    Sequence[Real]) are always widened, since the sibling overloads don't accept
    containers that mix both types.
    """
    # Group overloads by name within each module or class body
    overload_sets: dict[tuple[int, str], list[ast.FunctionDef]] = {}
    for node in ast.walk(ast.parse(stub)):
        for child in getattr(node, "body", []):
            if isinstance(child, ast.FunctionDef):
                overload_sets.setdefault((id(node), child.name), []).append(child)

    # Annotations to widen, and the widenings that apply to each
    annotations: list[tuple[ast.expr, list[Widening]]] = []
    for overloads in overload_sets.values():
        signatures = [signature(overload) for overload in overloads]
        for overload, sig in zip(overloads, signatures):
            for i, arg in enumerate(parameters(overload)):
                # Callbacks receive RealMatrix or Real, so their
                # annotations are left alone
                if arg is None or arg.annotation is None or is_callable(arg.annotation):
                    continue

                widenings = []
                for widening in WIDENINGS:
                    # Skip if a sibling overload already takes the source type
                    # here, unless the type is nested in a subscript
                    source_sig = sig.copy()
                    source_sig[i] = widening.pattern.sub(
                        widening.source, ast.unparse(arg.annotation)
                    )
                    if (
                        source_sig != sig
                        and source_sig in signatures
                        and not is_nested(arg.annotation, widening.pattern)
                    ):
                        continue

                    widenings.append(widening)

                annotations.append((arg.annotation, widenings))

    # Encode stub string into UTF-8 bytes
    source_bytes = stub.encode()

    # Compute byte offsets of each source line
    line_byte_offsets = [0]
    for line in source_bytes.splitlines(keepends=True):
        line_byte_offsets.append(line_byte_offsets[-1] + len(line))

    # Edit back to front so earlier offsets stay valid
    for annotation, widenings in sorted(
        annotations,
        key=lambda item: (item[0].lineno, item[0].col_offset),
        reverse=True,
    ):
        # Assertions to satisfy mypy. They can't fail in practice because
        # ast.parse() always sets those fields.
        assert annotation.end_lineno is not None
        assert annotation.end_col_offset is not None

        # Compute annotation's byte offsets relative to start of file
        start = line_byte_offsets[annotation.lineno - 1] + annotation.col_offset
        end = line_byte_offsets[annotation.end_lineno - 1] + annotation.end_col_offset

        # Splice widened type annotations into source_bytes
        widened = source_bytes[start:end].decode()
        for widening in widenings:
            widened = widening.pattern.sub(widening.widened, widened)
        source_bytes = source_bytes[:start] + widened.encode() + source_bytes[end:]
    return source_bytes.decode()


def fix_sparse_matrices(stub: str) -> str:
    """
    Replaces the float and complex type arguments of scipy.sparse.csc_matrix and
    scipy.sparse.csr_matrix with numpy.float64 and numpy.complex128, since
    scipy-stubs requires a NumPy numeric scalar type argument.
    """
    scalars = {"float": "numpy.float64", "complex": "numpy.complex128"}
    return re.sub(
        r"scipy\.sparse\.(cs[cr]_matrix)\[(float|complex)\]",
        lambda match: f"scipy.sparse.{match[1]}[{scalars[match[2]]}]",
        stub,
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "stubs",
        nargs="+",
        type=Path,
        help="stub files (.pyi) to fix up in place",
    )
    args = parser.parse_args()

    for path in args.stubs:
        stub = path.read_text(encoding="utf-8")
        stub = widen_signatures(stub)
        stub = fix_sparse_matrices(stub)
        path.write_text(stub, encoding="utf-8")


if __name__ == "__main__":
    main()

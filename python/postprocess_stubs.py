#!/usr/bin/env python

"""
Fixes up type stubs generated by nanobind's stubgen.

stubgen can't express some things the bindings support at runtime:

1. Implicit conversions widen what parameters accept: VariableBlock and
   UnitVector convert to VariableMatrix, and float converts to Variable. Every
   VariableMatrix parameter also accepts a VariableBlock and a UnitVector, and
   every Variable parameter also accepts a float. Return types and callback
   arguments are left alone since those are always VariableMatrix or Variable.
2. Sparse matrices are annotated as scipy.sparse.csc_matrix[float], but
   scipy-stubs expects a NumPy numeric scalar type argument.
"""

import argparse
import ast
import re
from dataclasses import dataclass
from pathlib import Path

PREFIX = r"(?:sleipnir\._sleipnir\.autodiff\.)?"

# VariableMatrix, optionally module-qualified. The lookahead prevents
# already-widened annotations from matching again.
#
#   x: VariableMatrix | None
#   -> x: VariableMatrix | VariableBlock | None
VARIABLE_MATRIX = re.compile(
    rf"""
    (?<![\w.])                         # Not part of another name
    ({PREFIX})                         # Optional module prefix
    VariableMatrix\b                   # Type name
    (?!\ \|\ {PREFIX}VariableBlock\b)  # Not already widened
    """,
    re.VERBOSE,
)

# VariableMatrix, optionally module-qualified and already widened with
# VariableBlock. The possessive quantifier keeps the VariableBlock from being
# dropped to get past the lookahead, which prevents already-widened annotations
# from matching again.
#
#   x: VariableMatrix | VariableBlock | None
#   -> x: VariableMatrix | VariableBlock | UnitVector | None
VARIABLE_MATRIX_FOR_UNIT_VECTOR = re.compile(
    rf"""
    (?<![\w.])                             # Not part of another name
    ({PREFIX})                             # Optional module prefix
    VariableMatrix\b                       # Type name
    (\ \|\ {PREFIX}VariableBlock\b)?+       # Optional VariableBlock widening
    (?!\ \|\ {PREFIX}UnitVector\b)          # Not already widened
    """,
    re.VERBOSE,
)

# Variable, optionally module-qualified. The word boundary excludes
# VariableMatrix and VariableBlock, and the lookahead prevents already-widened
# annotations from matching again.
#
#   x: Sequence[Variable]
#   -> x: Sequence[Variable | float]
VARIABLE = re.compile(
    rf"""
    (?<![\w.])         # Not part of another name
    ({PREFIX})         # Optional module prefix
    Variable\b         # Type name
    (?!\ \|\ float\b)  # Not already widened
    """,
    re.VERBOSE,
)


@dataclass(frozen=True)
class Widening:
    """A type that also accepts another type via implicit conversion."""

    # Matches the narrow type
    pattern: re.Pattern[str]

    # Replaces the narrow type with the type that converts to it
    source: str

    # Replaces the narrow type with the widened type
    widened: str


# \1 is "sleipnir._sleipnir.autodiff." prefix or empty
WIDENINGS = [
    Widening(
        VARIABLE_MATRIX, r"\1VariableBlock", r"\1VariableMatrix | \1VariableBlock"
    ),
    Widening(
        VARIABLE_MATRIX_FOR_UNIT_VECTOR,
        r"\1UnitVector",
        r"\1VariableMatrix\2 | \1UnitVector",
    ),
    Widening(VARIABLE, "float", r"\1Variable | float"),
]


def is_callable(annotation: ast.expr) -> bool:
    """Returns True if an annotation contains a Callable type."""
    return any(
        (isinstance(node, ast.Name) and node.id == "Callable")
        or (isinstance(node, ast.Attribute) and node.attr == "Callable")
        for node in ast.walk(annotation)
    )


def is_nested(annotation: ast.expr, pattern: re.Pattern[str]) -> bool:
    """
    Returns True if a type matching the pattern appears inside a subscript of
    an annotation (e.g., Variable in Sequence[Variable]).
    """
    return any(
        isinstance(node, ast.Subscript) and pattern.search(ast.unparse(node.slice))
        for node in ast.walk(annotation)
    )


def parameters(node: ast.FunctionDef) -> list[ast.arg | None]:
    """Returns a function's parameters in signature order."""
    args = node.args
    return [
        *args.posonlyargs,
        None,  # Separates positional-only parameters from the rest
        *args.args,
        args.vararg,
        *args.kwonlyargs,
        args.kwarg,
    ]


def signature(node: ast.FunctionDef) -> list[str | None]:
    """Returns a function's parameter annotations as source strings."""
    return [
        None if arg is None or arg.annotation is None else ast.unparse(arg.annotation)
        for arg in parameters(node)
    ]


def widen_signatures(stub: str) -> str:
    """
    Widens every VariableMatrix in function parameter annotations to
    VariableMatrix | VariableBlock | UnitVector, and every Variable to
    Variable | float.

    A parameter isn't widened if a sibling overload is identical except it
    takes the source type there (e.g., float instead of Variable); widening it
    would make that overload unreachable. Types nested in a subscript (e.g.,
    Sequence[Variable]) are always widened, since the sibling overloads don't
    accept containers that mix both types.
    """
    # Group overloads by name within each module or class body
    overload_sets: dict[tuple[int, str], list[ast.FunctionDef]] = {}
    for node in ast.walk(ast.parse(stub)):
        for child in getattr(node, "body", []):
            if isinstance(child, ast.FunctionDef):
                overload_sets.setdefault((id(node), child.name), []).append(child)

    # Annotations to widen, and the widenings that apply to each
    annotations: list[tuple[ast.expr, list[Widening]]] = []
    for overloads in overload_sets.values():
        signatures = [signature(overload) for overload in overloads]
        for overload, sig in zip(overloads, signatures):
            for i, arg in enumerate(parameters(overload)):
                # Callbacks receive VariableMatrix or Variable, so their
                # annotations are left alone
                if arg is None or arg.annotation is None or is_callable(arg.annotation):
                    continue

                widenings = []
                for widening in WIDENINGS:
                    # Skip if a sibling overload already takes the source type
                    # here, unless the type is nested in a subscript
                    source_sig = sig.copy()
                    source_sig[i] = widening.pattern.sub(
                        widening.source, ast.unparse(arg.annotation)
                    )
                    if (
                        source_sig != sig
                        and source_sig in signatures
                        and not is_nested(arg.annotation, widening.pattern)
                    ):
                        continue

                    widenings.append(widening)

                annotations.append((arg.annotation, widenings))

    # Encode stub string into UTF-8 bytes
    source_bytes = stub.encode()

    # Compute byte offsets of each source line
    line_byte_offsets = [0]
    for line in source_bytes.splitlines(keepends=True):
        line_byte_offsets.append(line_byte_offsets[-1] + len(line))

    # Edit back to front so earlier offsets stay valid
    for annotation, widenings in sorted(
        annotations,
        key=lambda item: (item[0].lineno, item[0].col_offset),
        reverse=True,
    ):
        # Assertions to satisfy mypy. They can't fail in practice because
        # ast.parse() always sets those fields.
        assert annotation.end_lineno is not None
        assert annotation.end_col_offset is not None

        # Compute annotation's byte offsets relative to start of file
        start = line_byte_offsets[annotation.lineno - 1] + annotation.col_offset
        end = line_byte_offsets[annotation.end_lineno - 1] + annotation.end_col_offset

        # Splice widened type annotations into source_bytes
        widened = source_bytes[start:end].decode()
        for widening in widenings:
            widened = widening.pattern.sub(widening.widened, widened)
        source_bytes = source_bytes[:start] + widened.encode() + source_bytes[end:]
    return source_bytes.decode()


def fix_sparse_matrices(stub: str) -> str:
    """
    Replaces scipy.sparse.csc_matrix[float] with
    scipy.sparse.csc_matrix[numpy.float64], since scipy-stubs requires a NumPy
    numeric scalar type argument.
    """
    return stub.replace(
        "scipy.sparse.csc_matrix[float]", "scipy.sparse.csc_matrix[numpy.float64]"
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "stubs",
        nargs="+",
        type=Path,
        help="stub files (.pyi) to fix up in place",
    )
    args = parser.parse_args()

    for path in args.stubs:
        stub = path.read_text(encoding="utf-8")
        stub = widen_signatures(stub)
        stub = fix_sparse_matrices(stub)
        path.write_text(stub, encoding="utf-8")


if __name__ == "__main__":
    main()
